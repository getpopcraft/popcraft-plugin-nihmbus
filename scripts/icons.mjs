#!/usr/bin/env node
// Inline assets/icon-*.svg as data: URLs into manifest.json (the panel's rail icon) and main.js (the icons the plugin
// switches between), and point the listing icon at the colour mark in this repo. A .json bundle carries no files, so icons travel inline.
//   node scripts/icons.mjs           write them
//   node scripts/icons.mjs --check   fail when main.js or manifest.json is out of date
import { readFileSync, writeFileSync } from 'node:fs'
import * as prettier from 'prettier'

// Base64: PopCraft takes no other data: icon in a manifest.
const dataUrl = (file) =>
  'data:image/svg+xml;base64,' +
  Buffer.from(readFileSync(new URL(`../assets/${file}`, import.meta.url), 'utf8').trim()).toString('base64')
const outline = dataUrl('icon-outline.svg')
const color = dataUrl('icon-color.svg')

const manifestPath = 'manifest.json'
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
// The listing icon is a URL (PopCraft caps it at 2 KB): the colour mark, served from this repo.
manifest.icon = 'https://raw.githubusercontent.com/getpopcraft/popcraft-plugin-nihmbus/main/assets/icon-color.svg'
for (const p of manifest.contributes?.panels ?? []) p.icon = outline
// Formatted exactly as `prettier --write` would, so the check and the linter agree.
const format = async (text, filepath) =>
  prettier.format(text, { ...(await prettier.resolveConfig(filepath)), filepath })
const nextManifest = await format(JSON.stringify(manifest, null, 2), manifestPath)

const mainPath = 'main.js'
const main = readFileSync(mainPath, 'utf8')
const block = `// <icons> generated by scripts/icons.mjs from assets/ — do not edit\nconst ICONS = { outline: ${JSON.stringify(outline)}, color: ${JSON.stringify(color)} }\n// </icons>`
const nextMain = await format(main.replace(/\/\/ <icons>[\s\S]*?\/\/ <\/icons>/, block), mainPath)
if (!main.includes('// <icons>')) throw new Error('main.js has no // <icons> block')

if (process.argv.includes('--check')) {
  const stale = [
    nextManifest !== readFileSync(manifestPath, 'utf8') && manifestPath,
    nextMain !== main && mainPath,
  ].filter(Boolean)
  if (stale.length) {
    console.error(`✖ out of date: ${stale.join(', ')}. Run node scripts/icons.mjs`)
    process.exit(1)
  }
  console.log('✓ icons up to date')
} else {
  writeFileSync(manifestPath, nextManifest)
  writeFileSync(mainPath, nextMain)
  console.log(`icons: outline ${outline.length} B, color ${color.length} B`)
}
